// 1xx — ინფორმაციული
// 100 Continue – მოთხოვნა მიღებულია, გააგრძელე.
// 2xx — წარმატებული
// 200 OK – მოთხოვნა წარმატებით შესრულდა.
// 201 Created – რესურსი წარმატებით შეიქმნა.
// 204 No Content – წარმატებული პასუხი, მაგრამ მონაცემების გარეშე.
// 3xx — გადამისამართება
// 301 Moved Permanently – რესურსი სამუდამოდ გადატანილია.
// 302 Found – დროებითი გადამისამართება.
// 304 Not Modified – რესურსი არ შეცვლილა.
// 4xx — კლიენტის შეცდომა
// 400 Bad Request – არასწორი მოთხოვნა.
// 401 Unauthorized – ავტორიზაცია საჭიროა.
// 403 Forbidden – წვდომა აკრძალულია.
// 404 Not Found – რესურსი ვერ მოიძებნა.
// 5xx — სერვერის შეცდომა
// 500 Internal Server Error – სერვერის შიდა შეცდომა.
// 502 Bad Gateway – არასწორი პასუხი სხვა სერვერიდან.
